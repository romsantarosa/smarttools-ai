export function inferCompanyByShipName(shipName: string): string {
  const normalized = shipName.toUpperCase().trim();

  if (normalized.startsWith('MSC ')) return 'MSC';
  if (normalized.startsWith('MAERSK ')) return 'MAERSK';
  if (normalized.startsWith('CMA CGM ')) return 'CMA CGM';
  if (normalized.startsWith('ONE ')) return 'ONE';
  if (normalized.startsWith('ZIM ')) return 'ZIM';
  if (normalized.startsWith('LOG-IN ')) return 'LOG-IN';
  if (normalized.startsWith('HAPAG ')) return 'HAPAG-LLOYD';

  return 'OUTROS';
}

